package org.apache.pekko.persistence.r2dbc.internal.oracle

import scala.concurrent.duration.Duration
import scala.concurrent.duration.FiniteDuration

import org.apache.pekko
import pekko.annotation.InternalApi
import pekko.persistence.r2dbc.internal.SettingsTypes

/**
 * INTERNAL API
 */
@InternalApi
private[r2dbc] object OracleUtils {

  /**
   * The current time in UTC, matching the UTC `TIMESTAMP` columns of the Oracle DDL.
   */
  val currentTimestampSql: String = "SYS_EXTRACT_UTC(SYSTIMESTAMP)"

  /**
   * The 10 second bucket of the `db_timestamp` column, as seconds since epoch divided by 10. The whole minutes are
   * counted with date arithmetic, which is rounded because a minute isn't exact in fractions of a day, and the seconds
   * are taken from the timestamp, so that fractional seconds don't move a timestamp into the next bucket.
   */
  val bucketSql: String =
    "ROUND((TRUNC(db_timestamp, 'MI') - DATE '1970-01-01') * 8640) + FLOOR(EXTRACT(SECOND FROM db_timestamp) / 10)"

  def behindCurrentTimeIntervalCondition(behindCurrentTime: FiniteDuration): String =
    if (behindCurrentTime > Duration.Zero)
      s"AND db_timestamp < $currentTimestampSql - NUMTODSINTERVAL(${behindCurrentTime.toMicros} / 1000000, 'SECOND')"
    else ""

  def settingRequirements(settings: SettingsTypes.AppTimestampSettings): Unit = {
    // Oracle has no transaction timestamp like Postgres, and the driver doesn't support RETURNING in the insert SQL,
    // so the timestamps are generated by the application, as for MySQL.
    require(settings.useAppTimestamp, "use-app-timestamp config must be on for Oracle support")
    require(
      settings.dbTimestampMonotonicIncreasing,
      "db-timestamp-monotonic-increasing config must be on for Oracle support")
  }
}
